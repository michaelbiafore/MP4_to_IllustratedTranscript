#!/usr/bin/env python3
"""
Course Capture Helper — records Quantra video lessons via OBS screen recording.

Opens each lesson URL in your normal Chrome browser (which has Widevine DRM and
your logged-in session), and controls OBS Studio via its WebSocket API to
start/stop recording for each video.

Semi-automated: the script opens each URL and starts recording, then you press
Enter when the video finishes. The script stops recording and moves to the next.

Usage:
  python scripts/course_capture_helper.py --sections 1,2
  python scripts/course_capture_helper.py --sections 1,2 --timeout 300  # 5-min auto-stop

Prerequisites:
  1. OBS Studio running with obs-websocket enabled (Tools > WebSocket Server Settings)
     - Enable WebSocket server on port 4455 (no auth needed for local use)
  2. OBS scene with a "Window Capture" source capturing Chrome
  3. Be logged into Quantra in Chrome
  4. Input/courses/quantra_380_structure.json (auto-generated by API extraction)
  5. pip install obsws-python
"""

import asyncio
import json
import os
import re
import shutil
import subprocess
import sys
import argparse
import time
from pathlib import Path


# ---------------------------------------------------------------------------
# OBS WebSocket helpers
# ---------------------------------------------------------------------------

class OBSController:
    """Control OBS Studio recording via obs-websocket v5."""

    def __init__(self, host: str = "localhost", port: int = 4455, password: str = ""):
        try:
            import obsws_python as obs
        except ImportError:
            print("ERROR: obsws-python not installed. Run:")
            print("  .venv/Scripts/python.exe -m pip install obsws-python")
            sys.exit(1)

        self._obs = obs
        self.host = host
        self.port = port
        self.password = password
        self.client = None

    def connect(self):
        """Connect to OBS WebSocket server."""
        try:
            self.client = self._obs.ReqClient(
                host=self.host, port=self.port, password=self.password, timeout=5
            )
            ver = self.client.get_version()
            print(f"  OBS connected: v{ver.obs_version} (websocket v{ver.obs_web_socket_version})")
            return True
        except Exception as e:
            print(f"ERROR: Cannot connect to OBS WebSocket at {self.host}:{self.port}")
            print(f"  {e}")
            print()
            print("Make sure OBS Studio is running and WebSocket Server is enabled:")
            print("  OBS > Tools > WebSocket Server Settings > Enable WebSocket Server")
            return False

    def disconnect(self):
        if self.client:
            self.client.disconnect()

    def get_record_directory(self) -> str:
        resp = self.client.get_record_directory()
        return resp.record_directory

    def set_record_directory(self, path: str):
        self.client.set_record_directory(path)

    def start_recording(self):
        self.client.start_record()

    def stop_recording(self) -> str:
        resp = self.client.stop_record()
        return resp.output_path

    def get_record_status(self) -> dict:
        resp = self.client.get_record_status()
        return {
            "active": resp.output_active,
            "paused": resp.output_paused,
        }


# ---------------------------------------------------------------------------
# Utility functions
# ---------------------------------------------------------------------------

def slugify(text: str) -> str:
    """Convert text to a safe filename fragment."""
    safe = re.sub(r'[^a-zA-Z0-9_-]', '_', text.strip())
    safe = re.sub(r'_+', '_', safe)
    return safe[:50].strip('_')


def load_course_structure(structure_path: Path) -> list[dict]:
    """Load and return sections from the course structure JSON."""
    data = json.loads(structure_path.read_text(encoding="utf-8"))
    return data["result"]["sections"]


def get_video_units(sections: list[dict], section_filter: list[int] | None = None) -> list[dict]:
    """Extract video units from sections, optionally filtering by section number."""
    units = []
    for s in sections:
        s_no = s["section_no"]
        if section_filter and s_no not in section_filter:
            continue
        s_name = s["sectionName"]
        for u in s.get("units", []):
            u_type = u.get("unitType", u.get("unit_type", ""))
            if "Video" not in u_type:
                continue
            u_no = u.get("unitNo", u.get("unit_no", 0))
            u_name = u.get("unitName", u.get("unit_name", "Unknown"))
            units.append({
                "section_no": s_no,
                "section_name": s_name,
                "unit_no": u_no,
                "unit_name": u_name,
                "unit_type": u_type,
            })
    return units


def open_in_browser(url: str):
    """Open URL in the default browser (normal Chrome with DRM support)."""
    if sys.platform == "win32":
        os.startfile(url)
    elif sys.platform == "darwin":
        subprocess.run(["open", url])
    else:
        subprocess.run(["xdg-open", url])


# ---------------------------------------------------------------------------
# Main capture loop
# ---------------------------------------------------------------------------

def run_capture(video_units: list[dict], obs: OBSController, output_dir: Path,
                timeout_seconds: int | None = None):
    """Semi-automated capture: opens URL in Chrome, OBS records, user presses Enter."""
    captured = 0

    for i, unit in enumerate(video_units, 1):
        s_no = unit["section_no"]
        u_no = unit["unit_no"]
        name = unit["unit_name"]
        name_slug = slugify(name)

        mp4_name = f"s{s_no:02d}_{u_no:02d}_{name_slug}.mp4"
        mp4_path = output_dir / mp4_name

        if mp4_path.exists():
            print(f"[{i}/{len(video_units)}] SKIP (exists): {mp4_name}")
            captured += 1
            continue

        print(f"\n{'─'*60}")
        print(f"[{i}/{len(video_units)}] S{s_no} U{u_no}: {name}")
        print(f"{'─'*60}")

        url = (
            f"https://quantra.quantinsti.com/startCourseDetails"
            f"?cid=380&section_no={s_no}&unit_no={u_no}"
            f"&course_type=paid&unit_type=Video"
        )

        # Open in normal Chrome
        print(f"  Opening: {url}")
        open_in_browser(url)

        # Give Chrome time to load
        print(f"  Waiting 8 seconds for page to load...")
        time.sleep(8)

        # Start OBS recording
        print(f"  ▶ OBS recording STARTED")
        obs.start_recording()

        if timeout_seconds:
            # Fully automated: wait for timeout
            print(f"  Auto-stop in {timeout_seconds} seconds...")
            print(f"  (Press Enter to stop early, or wait for timeout)")
            import select
            # On Windows, select doesn't work on stdin. Use a thread approach.
            import threading
            stop_event = threading.Event()

            def wait_for_enter():
                sys.stdin.readline()
                stop_event.set()

            input_thread = threading.Thread(target=wait_for_enter, daemon=True)
            input_thread.start()

            elapsed = 0
            while elapsed < timeout_seconds and not stop_event.is_set():
                time.sleep(1)
                elapsed += 1
                mins = elapsed // 60
                secs = elapsed % 60
                print(f"\r  Recording: {mins}:{secs:02d} / {timeout_seconds // 60}:{timeout_seconds % 60:02d}", end="", flush=True)

            print()  # newline after progress
        else:
            # Semi-automated: wait for user
            print()
            print(f"  ╔══════════════════════════════════════════════╗")
            print(f"  ║  Play the video in Chrome.                  ║")
            print(f"  ║  When it finishes, press ENTER here.        ║")
            print(f"  ║  Type 'q' + Enter to quit early.            ║")
            print(f"  ╚══════════════════════════════════════════════╝")

            user_input = sys.stdin.readline().strip().lower()
            if user_input == "q":
                print("\n  Stopping recording and quitting...")
                obs_output = obs.stop_recording()
                print(f"  ■ OBS recording STOPPED: {obs_output}")
                break

        # Stop OBS recording
        obs_output = obs.stop_recording()
        print(f"  ■ OBS recording STOPPED")
        print(f"    OBS saved: {obs_output}")

        # Wait for OBS to finalize the file
        time.sleep(2)

        # Rename OBS output to our naming convention
        if obs_output and Path(obs_output).exists():
            obs_file = Path(obs_output)
            # Keep the extension OBS used (mp4, mkv, etc.)
            target = output_dir / f"{mp4_path.stem}{obs_file.suffix}"
            try:
                shutil.move(str(obs_file), str(target))
                print(f"    Renamed to: {target.name}")
                captured += 1
            except Exception as e:
                print(f"    WARNING: Could not rename: {e}")
                captured += 1  # File exists, just not renamed
        else:
            print(f"    WARNING: OBS output not found at {obs_output}")

    return captured


def main(args):
    structure_path = Path("Input/courses/quantra_380_structure.json")
    if not structure_path.exists():
        print(f"ERROR: Course structure not found: {structure_path}")
        sys.exit(1)

    sections = load_course_structure(structure_path)

    section_filter = None
    if args.sections:
        section_filter = [int(s.strip()) for s in args.sections.split(",")]

    video_units = get_video_units(sections, section_filter)

    if not video_units:
        print("No video units found for the specified sections.")
        sys.exit(0)

    output_dir = Path("Input/courses/quantra_380/raw")
    output_dir.mkdir(parents=True, exist_ok=True)
    output_abs = str(output_dir.resolve())

    print(f"\n{'='*60}")
    print(f"  QUANTRA COURSE CAPTURE")
    print(f"  Course 380: Agentic AI for Trading")
    print(f"  Sections: {args.sections or 'all'}")
    print(f"  Video units to capture: {len(video_units)}")
    if args.timeout:
        print(f"  Mode: AUTO-STOP after {args.timeout}s per video")
    else:
        print(f"  Mode: SEMI-AUTO (press Enter after each video)")
    print(f"  Output: {output_dir}")
    print(f"{'='*60}")

    for i, u in enumerate(video_units, 1):
        print(f"  {i}. S{u['section_no']} U{u['unit_no']}: {u['unit_name']}")

    # Connect to OBS
    print()
    obs = OBSController(
        host=args.obs_host,
        port=args.obs_port,
        password=args.obs_password,
    )
    if not obs.connect():
        sys.exit(1)

    # Set OBS recording directory
    obs.set_record_directory(output_abs)
    print(f"  OBS recording dir: {output_abs}")

    print()
    print("  INSTRUCTIONS:")
    print("  1. Make sure Chrome is visible and OBS is capturing the Chrome window")
    print("  2. Each video URL will open in a new Chrome tab")
    print("  3. Click play on the video when it loads")
    print("  4. Press Enter in this terminal when the video finishes")
    print()
    input("  Press Enter to begin capture...")

    captured = run_capture(
        video_units, obs, output_dir,
        timeout_seconds=args.timeout,
    )

    obs.disconnect()

    print(f"\n{'='*60}")
    print(f"  CAPTURE COMPLETE: {captured} / {len(video_units)} videos")
    print()
    print("  Next steps:")
    print("  1. Normalize: bash scripts/normalize_clips.sh Input/courses/quantra_380/raw Input/courses/quantra_380/normalized")
    print("  2. Fuse: bash scripts/fuse_clips.sh Input/courses/quantra_380/normalized Input/courses/quantra_380/merged/quantra_380.mp4")
    print("  3. Transcribe with Whisper, then /format-transcript and /slidefy-transcript")
    print(f"{'='*60}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Capture Quantra course videos")
    parser.add_argument("--sections", default=None,
                        help="Comma-separated section numbers (e.g., '1,2'). Default: all")
    parser.add_argument("--timeout", type=int, default=None,
                        help="Auto-stop recording after N seconds per video (default: manual Enter)")
    parser.add_argument("--obs-host", default="localhost",
                        help="OBS WebSocket host (default: localhost)")
    parser.add_argument("--obs-port", type=int, default=4455,
                        help="OBS WebSocket port (default: 4455)")
    parser.add_argument("--obs-password", default="",
                        help="OBS WebSocket password (default: empty)")
    args = parser.parse_args()
    main(args)
